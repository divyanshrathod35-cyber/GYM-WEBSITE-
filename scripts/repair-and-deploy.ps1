#requires -Version 5.1
<#
BODY TECH GYM - Safe repair and production deployment.
Run from the existing repository:
powershell.exe -NoProfile -ExecutionPolicy Bypass -File ".\scripts\repair-and-deploy.ps1"

No force-push, deletion, billing change, or disabling deployment protection.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"
$Repo = "divyanshrathod35-cyber/GYM-WEBSITE-"
$Team = "div-dev4"
$ExpectedOrgId = "team_TrdKvpsgR5LN3FrRFOHaWspX"
$Project = "bodytech-gym"
$ExpectedProjectId = "prj_oN43vGId2xpMg7WMy9Pr9diNAFl1"
$Root = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot "..")).Path

function Banner([string]$Message) {
    Write-Host ""
    Write-Host "=== $Message ===" -ForegroundColor Cyan
}
function CheckExit([string]$Action) {
    if ($LASTEXITCODE -ne 0) {
        throw "$Action failed (exit code $LASTEXITCODE). See the error above."
    }
}
function RequireCommand([string]$Command) {
    if (-not (Get-Command $Command -ErrorAction SilentlyContinue)) {
        throw "$Command not found. Reopen PowerShell after installing Git, Node.js or Vercel CLI."
    }
}

Banner "01 / Verify existing GitHub checkout"
RequireCommand "git.exe"
RequireCommand "npm.cmd"
RequireCommand "vercel.cmd"
if (-not (Test-Path -LiteralPath (Join-Path $Root ".git") -PathType Container)) {
    throw "Not an existing Git checkout: $Root"
}
$Origin = (& git.exe -C $Root remote get-url origin).Trim()
CheckExit "Read Git remote"
if ($Origin -notmatch '(?i)github\.com[:/]divyanshrathod35-cyber/GYM-WEBSITE-(\.git)?$') {
    throw "Unexpected Git repository: $Origin"
}
$TrackedChanges = @(& git.exe -C $Root status --porcelain --untracked-files=no)
CheckExit "Inspect tracked changes"
if ($TrackedChanges.Count -gt 0) {
    throw "Tracked local changes exist. Commit or back them up before pulling. Nothing was overwritten."
}
$Branch = (& git.exe -C $Root branch --show-current).Trim()
CheckExit "Inspect current branch"
if ($Branch -ne "main") {
    throw "Current branch is '$Branch', expected 'main'. Select main deliberately before rerunning."
}
& git.exe -C $Root fetch origin main
CheckExit "Fetch GitHub main"
& git.exe -C $Root merge --ff-only origin/main
CheckExit "Fast-forward GitHub main"
Set-Location -LiteralPath $Root
$Commit = (& git.exe rev-parse HEAD).Trim()
CheckExit "Read commit"
Write-Host "Repository: $Repo"
Write-Host "Commit: $Commit"

Banner "02 / Verify dependencies and run tests"
if (-not (Test-Path -LiteralPath (Join-Path $Root "node_modules\typescript"))) {
    Write-Host "Dependencies missing, running npm install..."
    & npm.cmd install --no-audit --no-fund
    CheckExit "npm install"
}
& npm.cmd test
CheckExit "Unit tests"
& npm.cmd run typecheck
CheckExit "TypeScript verification"
& npm.cmd run build
CheckExit "Vite production build"
if (-not (Test-Path -LiteralPath (Join-Path $Root "dist\index.html") -PathType Leaf)) {
    throw "Production build did not create dist\index.html."
}
Write-Host "PASS: Unit tests, TypeScript and production Vite build." -ForegroundColor Green

Banner "03 / Confirm direct Vercel CLI authentication"
& vercel.cmd whoami
if ($LASTEXITCODE -ne 0) {
    & vercel.cmd login
    CheckExit "Vercel browser login"
}
& vercel.cmd teams ls
CheckExit "List accessible Vercel teams"

Banner "04 / Find or create correctly named project"
& vercel.cmd project inspect $Project --scope $Team
if ($LASTEXITCODE -ne 0) {
    Write-Host "Could not inspect $Project. Attempting to create in $Team..."
    & vercel.cmd project add $Project --scope $Team
    CheckExit "Vercel project creation; if 403 persists, repair team/API permissions"
}
& vercel.cmd link --yes --project $Project --scope $Team
CheckExit "Link local source to Vercel project"
$ConfigPath = Join-Path $Root ".vercel\project.json"
if (-not (Test-Path -LiteralPath $ConfigPath -PathType Leaf)) {
    throw ".vercel\project.json was not generated by Vercel CLI."
}
$LinkConfig = Get-Content -LiteralPath $ConfigPath -Raw | ConvertFrom-Json
if ($LinkConfig.orgId -ne $ExpectedOrgId) {
    throw "Safety stop: linked to $($LinkConfig.orgId), expected $ExpectedOrgId (DIV-DEV)."
}
if ($LinkConfig.projectId -ne $ExpectedProjectId) {
    throw "Safety stop: linked to project $($LinkConfig.projectId), expected $ExpectedProjectId."
}

Banner "05 / Package successful Vite build as Vercel static output"
Write-Host "Bypassing Windows Vercel builder symlinks; using Build Output API v3."
& vercel.cmd pull --yes --environment production --scope $Team
CheckExit "Pull production project settings"
$DistPath = (Resolve-Path -LiteralPath (Join-Path $Root "dist")).Path
$OutputPath = Join-Path $Root ".vercel\output"
$StaticPath = Join-Path $OutputPath "static"
$OutputConfig = Join-Path $OutputPath "config.json"
if (Test-Path -LiteralPath $OutputPath) {
    $OutputItem = Get-Item -LiteralPath $OutputPath -Force
    if (($OutputItem.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "Refusing to replace Vercel output because the directory is a junction or symlink."
    }
    Remove-Item -LiteralPath $OutputPath -Recurse -Force
}
New-Item -ItemType Directory -Path $StaticPath -Force | Out-Null
$DistFiles = @(Get-ChildItem -LiteralPath $DistPath -Recurse -File -Force)
if ($DistFiles.Count -lt 4) {
    throw "Vite dist does not contain enough output files to publish."
}
foreach ($File in $DistFiles) {
    $RelativePath = $File.FullName.Substring($DistPath.Length + 1)
    $TargetFile = Join-Path $StaticPath $RelativePath
    $TargetFolder = Split-Path -Parent $TargetFile
    if (-not (Test-Path -LiteralPath $TargetFolder)) {
        New-Item -ItemType Directory -Path $TargetFolder -Force | Out-Null
    }
    Copy-Item -LiteralPath $File.FullName -Destination $TargetFile -Force
}
$Routes = @(
    @{
        src = "/(.*)"
        headers = @{
            "X-Content-Type-Options" = "nosniff"
            "Referrer-Policy" = "strict-origin-when-cross-origin"
            "X-Frame-Options" = "DENY"
            "X-Robots-Tag" = "noindex, nofollow, noarchive"
        }
        'continue' = $true
    },
    @{ handle = "filesystem" },
    @{ src = "/(.*)"; dest = "/index.html" }
)
$OutputManifest = @{ version = 3; routes = $Routes }
$Json = $OutputManifest | ConvertTo-Json -Depth 10
[System.IO.File]::WriteAllText(
    $OutputConfig,
    $Json,
    (New-Object System.Text.UTF8Encoding($false))
)
$ParsedManifest = Get-Content -LiteralPath $OutputConfig -Raw | ConvertFrom-Json
if ($ParsedManifest.version -ne 3) { throw "Invalid Vercel Build Output API version." }
if (-not (Test-Path -LiteralPath (Join-Path $StaticPath "index.html") -PathType Leaf)) {
    throw "Missing index.html from prepared Vercel static output."
}
foreach ($RequiredAsset in @("media\hero-strength.webp", "favicon.svg")) {
    if (-not (Test-Path -LiteralPath (Join-Path $StaticPath $RequiredAsset) -PathType Leaf)) {
        throw "Missing required static asset: $RequiredAsset"
    }
}
Write-Host ("Static deployment staged: {0} files; no symlinks required." -f $DistFiles.Count) -ForegroundColor Green

Banner "06 / Deploy prebuilt assets to production"
$DeployOutput = @(& vercel.cmd deploy --prebuilt --prod --yes --scope $Team)
$DeployExit = $LASTEXITCODE
$DeployOutput | ForEach-Object { Write-Host $_ }
if ($DeployExit -ne 0) {
    throw "Vercel deployment was rejected (exit $DeployExit). Inspect account permissions or quota."
}
$Urls = [regex]::Matches(($DeployOutput -join [Environment]::NewLine), 'https://[a-zA-Z0-9.-]+\.vercel\.app')
if ($Urls.Count -lt 1) {
    & vercel.cmd ls $Project --scope $Team
    throw "No deployment URL was returned. Check the deployment list above."
}
$LiveUrl = $Urls[$Urls.Count - 1].Value

Banner "07 / Inspect public site"
& vercel.cmd inspect $LiveUrl --scope $Team
CheckExit "Inspect Vercel deployment"
try {
    $Response = Invoke-WebRequest -Uri $LiveUrl -UseBasicParsing -TimeoutSec 40
    if ($Response.StatusCode -ne 200) {
        throw "HTTP $($Response.StatusCode)"
    }
    if ($Response.Content -notmatch 'Body Tech|BODY TECH|BODYTECH') {
        throw "Brand text missing in deployed HTML."
    }
}
catch {
    Write-Warning "Public verification failed: $($_.Exception.Message)"
    Write-Host "Deployment URL: $LiveUrl"
    throw "Review Deployment Protection and public accessibility before sharing."
}

Banner "08 / Git auto-deployment connection"
& vercel.cmd git connect --yes --scope $Team
if ($LASTEXITCODE -ne 0) {
    Write-Warning "Production deployment passed but automatic GitHub linking needs review."
}

Write-Host ""
Write-Host "BODY TECH GYM - PUBLIC DEPLOYMENT VERIFIED" -ForegroundColor Green
Write-Host "URL: $LiveUrl"
Write-Host "GitHub: https://github.com/$Repo"
Write-Host "Commit: $Commit"
Write-Host "Reminder: this is a pitch concept; verify pricing, hours, trials and imagery with owner."
